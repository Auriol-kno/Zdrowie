import { chromium, serve, IPHONE } from './helpers.mjs';
const OUT = process.argv[2] ?? '/tmp/claude-0/shots';
const { server, url } = await serve();
const b = await chromium.launch(); const ctx = await b.newContext({ ...IPHONE, serviceWorkers: 'block' });
const p = await ctx.newPage(); p.setDefaultTimeout(5000);
await p.goto(url); await p.waitForSelector('.app');
await p.getByRole('button', { name: 'Zaczynamy' }).click(); await p.getByLabel('Imię (opcjonalnie)').fill('Tomek');
for (let i = 0; i < 8; i++) await p.getByRole('button', { name: /Dalej|Utwórz plan/ }).click();
await p.waitForSelector('.tabbar');
await p.locator('.tab', { hasText: 'Trening' }).click();
const sb = p.getByRole('button', { name: /Rozpocznij trening/ }).first();
if (await sb.count()) await sb.click(); else await p.locator('.list-item', { hasText: /ćwiczeń · ok\./ }).first().click();
await p.waitForSelector('.coachbtn');
const shot = async (n) => { await p.waitForTimeout(300); await p.screenshot({ path: `${OUT}/${n}.png` }); };
await shot('50-coach-idle');
await p.locator('.coachbtn').click(); await p.waitForTimeout(3600); await shot('51-coach-running');
await b.close(); server.close();
